# Hold-to-repeat binding
# ---------------------------------------------------------------------------

def bind_hold_repeat(btn, action_fn, root,
                     initial_delay=HOLD_INITIAL_DELAY,
                     repeat_delay=HOLD_REPEAT_DELAY):
    """Press and hold a button to keep firing action_fn repeatedly."""
    _after_id = [None]

    def _repeat():
        action_fn()
        _after_id[0] = root.after(repeat_delay, _repeat)

    def _on_press(event):
        action_fn()
        _after_id[0] = root.after(initial_delay, _repeat)

    def _on_release(event):
        if _after_id[0] is not None:
            root.after_cancel(_after_id[0])
            _after_id[0] = None

    btn.config(command=lambda: None)   # disable normal click handler
    btn.bind("<ButtonPress-1>",   _on_press)
    btn.bind("<ButtonRelease-1>", _on_release)


