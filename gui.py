OV_WORLD_MIN = -20
OV_WORLD_MAX =  20
OV_W, OV_H   = 180, 180


def _world_to_ov(wx, wz):
    px = (wx - OV_WORLD_MIN) / (OV_WORLD_MAX - OV_WORLD_MIN) * OV_W
    py = (wz - OV_WORLD_MIN) / (OV_WORLD_MAX - OV_WORLD_MIN) * OV_H
    return px, py


class OverviewCanvas(tk.Canvas):
    def __init__(self, parent, **kw):
        super().__init__(parent, width=OV_W, height=OV_H,
                         bg=OVERVIEW_BG, highlightthickness=1,
                         highlightbackground=BORDER, **kw)
        self._draw_static()

    def _draw_static(self):
        step = OV_W / 8
        for i in range(9):
            x = i * step
            self.create_line(x, 0, x, OV_H, fill=GRID_LINE, width=1)
            self.create_line(0, x, OV_W, x, fill=GRID_LINE, width=1)
        cx, cy = OV_W // 2, OV_H // 2
        self.create_line(cx, 0, cx, OV_H, fill=BORDER, width=1)
        self.create_line(0, cy, OV_W, cy, fill=BORDER, width=1)
        for txt, ax, ay in [("X+", OV_W-12, 6), ("Z+", 5, OV_H-12)]:
            self.create_text(ax, ay, text=txt, fill=TEXT_DIM, font=("Courier", 7))

    def draw_shapes(self, scene_mode, shape_vars=None):
        self.delete("shape_marker")
        if scene_mode == SCENE_BASIC:
            for i, (wx, wz, r, fill) in enumerate(_OV_SHAPES_BASIC):
                if shape_vars and not shape_vars[i].get():
                    continue
                px, py = _world_to_ov(wx, wz)
                self.create_oval(px-r, py-r, px+r, py+r,
                                 fill=fill, outline="", tags="shape_marker")
        else:
            for wx, wz, r, fill, lbl in _OV_SHAPES_SOLAR:
                px, py = _world_to_ov(wx, wz)
                self.create_oval(px-r, py-r, px+r, py+r,
                                 fill=fill, outline="", tags="shape_marker")
                if lbl == "Panel":
                    # Highlight the solar panel with amber ring
                    self.create_oval(px-r-2, py-r-2, px+r+2, py+r+2,
                                     fill="", outline=LIGHT_CLR, width=1,
                                     tags="shape_marker")
                    self.create_text(px, py, text="☀", fill=LIGHT_CLR,
                                     font=("Helvetica", 7), tags="shape_marker")

    def update_light(self, lx, ly, lz):
        self.delete("light_marker")
        px, py = _world_to_ov(lx, lz)
        ly_norm = max(0.2, min(1.0, ly / 20.0))
        halo_r  = int(12 + ly_norm * 14)
        core_r  = 5
        self.create_oval(px-halo_r, py-halo_r, px+halo_r, py+halo_r,
                         fill="", outline=LIGHT_CLR, width=2, tags="light_marker")
        mid_r = halo_r // 2
        self.create_oval(px-mid_r, py-mid_r, px+mid_r, py+mid_r,
                         fill="", outline=ACCENT_DIM, width=1, tags="light_marker")
        self.create_oval(px-core_r, py-core_r, px+core_r, py+core_r,
                         fill=LIGHT_CLR, outline=ACCENT_HOV, width=1, tags="light_marker")
        self.create_text(px, py-halo_r-7, text="☀",
                         fill=LIGHT_CLR, font=("Helvetica", 8), tags="light_marker")
        self.create_text(px, py+halo_r+8,
                         text=f"({lx:+.0f}, {lz:+.0f})",
                         fill=TEXT_DIM, font=("Courier", 7), tags="light_marker")


