def load_ppm_as_photoimage(path):
    try:
        from PIL import Image, ImageTk
        return ImageTk.PhotoImage(Image.open(path))
    except ImportError:
        pass
    with open(path, "r") as f:
        tokens = f.read().split()
    assert tokens[0] == "P3"
    w, h, maxv = int(tokens[1]), int(tokens[2]), int(tokens[3])
    vals = list(map(int, tokens[4:]))
    img = tk.PhotoImage(width=w, height=h)
    for y in range(h):
        row, base = [], y * w * 3
        for x in range(w):
            r = vals[base + x*3]     * 255 // maxv
            g = vals[base + x*3 + 1] * 255 // maxv
            b = vals[base + x*3 + 2] * 255 // maxv
            row.append(f"#{r:02x}{g:02x}{b:02x}")
        img.put("{" + " ".join(row) + "}", to=(0, y))
    return img


def write_scene(light_pos, shape_lines):
    with open(SCENE_PATH, "w") as f:
        f.write("# generated by gui.py\n")
        f.write(f"light {light_pos[0]:.3f} {light_pos[1]:.3f} {light_pos[2]:.3f}\n")
        for line in shape_lines:
            f.write(line + "\n")


def run_raytracer(delete_region=None):
    cmd = [str(RAYTRACER),
           "--scene", str(SCENE_PATH),
           "--out",   str(OUTPUT_PPM),
           "--exposure-samples", str(EXPOSURE_N)]
    if delete_region:
        cmd += ["--delete-region"] + [str(v) for v in delete_region]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(
            f"raytracer failed:\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}")
    stats = {}
    for line in result.stdout.splitlines():
        parts = line.split(maxsplit=1)
        if len(parts) == 2:
            stats[parts[0]] = parts[1]
    return stats


