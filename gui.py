def make_btn(parent, text, command, color=ACCENT, hover=ACCENT_HOV,
             font=FONT_BOLD, padx=14, pady=6, width=None):
    kw = dict(text=text, command=command,
              bg=color, fg=BG,
              activebackground=hover, activeforeground=BG,
              relief="flat", bd=0,
              font=font, padx=padx, pady=pady,
              cursor="hand2")
    if width:
        kw["width"] = width
    btn = tk.Button(parent, **kw)
    btn.bind("<Enter>", lambda e: btn.config(bg=hover))
    btn.bind("<Leave>", lambda e: btn.config(bg=color))
    return btn


